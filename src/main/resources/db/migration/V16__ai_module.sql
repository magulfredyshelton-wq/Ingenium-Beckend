-- =====================================================================
--  V16 - Módulo de IA (tabelas ai_*, vetores e ligação às tags)
-- =====================================================================

-- vector = guarda embeddings no PostgreSQL (pg_trgm já foi criada na V13)
CREATE EXTENSION IF NOT EXISTS vector;

-- ---------- Chat ----------
CREATE TABLE ai_conversa (
                             id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             utilizador_id  VARCHAR(64)  NOT NULL,
                             titulo         VARCHAR(120) NOT NULL,
                             criada_em      TIMESTAMP(6) NOT NULL DEFAULT now(),
                             atualizada_em  TIMESTAMP(6) NOT NULL DEFAULT now()
);

CREATE TABLE ai_mensagem (
                             id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             conversa_id  BIGINT       NOT NULL REFERENCES ai_conversa(id) ON DELETE CASCADE,
                             papel        VARCHAR(12)  NOT NULL,
                             conteudo     TEXT         NOT NULL,
                             criada_em    TIMESTAMP(6) NOT NULL DEFAULT now()
);

-- ---------- Recomendações e registo de pedidos ----------
CREATE TABLE ai_recomendacao (
                                 id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 utilizador_id  VARCHAR(64)      NOT NULL,
                                 tipo           VARCHAR(20)      NOT NULL,
                                 alvo_id        VARCHAR(64)      NOT NULL,
                                 pontuacao      DOUBLE PRECISION NOT NULL,
                                 explicacao     TEXT,
                                 criada_em      TIMESTAMP(6)     NOT NULL DEFAULT now()
);

CREATE TABLE ai_pedido_log (
                               id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               utilizador_id  VARCHAR(64),
                               servico        VARCHAR(40)  NOT NULL,
                               duracao_ms     BIGINT       NOT NULL,
                               sucesso        BOOLEAN      NOT NULL,
                               erro           VARCHAR(500),
                               criado_em      TIMESTAMP(6) NOT NULL DEFAULT now()
);

-- ---------- Entidades indexadas (perfis, vagas, conhecimento) ----------
CREATE TABLE ai_entidade_indexada (
                                      id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      tipo           VARCHAR(20)  NOT NULL,
                                      referencia_id  VARCHAR(64)  NOT NULL,
                                      titulo         VARCHAR(255),
                                      texto          TEXT         NOT NULL,
                                      hash_conteudo  VARCHAR(64)  NOT NULL,
                                      ativa          BOOLEAN      NOT NULL DEFAULT true,
                                      atualizado_em  TIMESTAMP(6) NOT NULL DEFAULT now(),
                                      UNIQUE (tipo, referencia_id)
);

-- Liga cada entidade às TAGS da base de dados (substitui a taxonomia)
CREATE TABLE ai_entidade_tag (
                                 entidade_id  BIGINT NOT NULL REFERENCES ai_entidade_indexada(id) ON DELETE CASCADE,
                                 tag_id       UUID   NOT NULL REFERENCES tag(id),
                                 PRIMARY KEY (entidade_id, tag_id)
);

-- ---------- Base vetorial (o "R" do RAG) ----------
-- 768 = dimensões do gemini-embedding-001 (têm de coincidir com o application.properties)
CREATE TABLE ai_vector_store (
                                 id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                                 content    TEXT,
                                 metadata   JSON,
                                 embedding  vector(768)
);

CREATE INDEX idx_ai_vector_embedding ON ai_vector_store USING HNSW (embedding vector_cosine_ops);

-- ---------- Índices das consultas frequentes ----------
CREATE INDEX idx_ai_conversa_utilizador      ON ai_conversa (utilizador_id, atualizada_em DESC);
CREATE INDEX idx_ai_mensagem_conversa        ON ai_mensagem (conversa_id, id);
CREATE INDEX idx_ai_recomendacao_utilizador  ON ai_recomendacao (utilizador_id, criada_em DESC);
CREATE INDEX idx_ai_pedido_log_servico       ON ai_pedido_log (servico, criado_em DESC);
CREATE INDEX idx_ai_entidade_tag_tag         ON ai_entidade_tag (tag_id);